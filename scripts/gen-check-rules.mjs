#!/usr/bin/env node
/**
 * Generate apps/dev/src/content/check-rules.json — the rule inventory the
 * /check page shows under "What gets checked".
 *
 * Those counts used to be typed by hand, and had drifted twice: the page
 * advertised 53 rules across 6 categories while the checker actually had 82
 * across 7, and the GDD category was missing entirely. Deriving them from the
 * rule modules means the page cannot be wrong about its own behaviour.
 *
 * Each rule module owns exactly one category — that mapping is the only thing
 * declared here, because the ids themselves are read out of the source.
 *
 * Runs from `prebuild`, so a normal build always refreshes it.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));

/** Source file → the category every finding in it belongs to. */
const MODULES = {
  "apps/dev/src/lib/check/rules/manifest.ts": "manifest",
  "apps/dev/src/lib/check/rules/manifest-cross.ts": "manifest",
  "apps/dev/src/lib/check/rules/gdd.ts": "gdd",
  "apps/dev/src/lib/check/rules/structure.ts": "structure",
  "apps/dev/src/lib/check/rules/module.ts": "module",
  "apps/dev/src/lib/check/rules/styling.ts": "styling",
  "apps/dev/src/lib/check/rules/assets.ts": "assets",
  "apps/dev/src/lib/check/runtime/rules.ts": "runtime",
};

const RULE_ID = /"([A-Z]-\d{2})"/g;
/** id → the human title the rule reports, so the rules page needs no second source. */
const TITLED = /id:\s*"([A-Z]-\d{2})"[\s\S]{0,400}?title:\s*(?:`([^`]*)`|"([^"]*)")/g;
/** Rules raised through a helper, where severity sits in the call not the object. */
const PUSHED = /push\(\s*ctx\s*,\s*"([A-Z]-\d{2})"\s*,\s*"(\w+)"\s*,\s*"([^"]*)"/g;
const ADDED = /add\(\s*"([A-Z]-\d{2})"\s*,\s*"(\w+)"\s*,\s*(?:`([^`]*)`|"([^"]*)")/g;

const byCategory = new Map();
const titles = new Map();
for (const [file, category] of Object.entries(MODULES)) {
  const src = readFileSync(resolve(repoRoot, file), "utf8");
  const ids = [...src.matchAll(RULE_ID)].map((m) => m[1]);
  if (ids.length === 0) {
    console.warn(`warning: no rule ids found in ${file}`);
  }
  if (!byCategory.has(category)) byCategory.set(category, new Set());
  for (const id of ids) byCategory.get(category).add(id);

  // Titles are best-effort: a rule that reports several different titles keeps
  // the first, which is enough for an index. The page links to the spec, not to
  // an exhaustive restatement of every message.
  for (const re of [TITLED, PUSHED, ADDED]) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(src))) {
      const id = m[1];
      const title = (m[4] ?? m[3] ?? m[2] ?? "").trim();
      // Titles built from template literals carry ${…} interpolations; strip
      // them rather than printing the source of a message on a reference page.
      const clean = title.replace(/\$\{[^}]*\}/g, "…").replace(/\s+/g, " ").trim();
      if (clean && !/^(error|warning|info|pass)$/.test(clean) && !titles.has(id)) titles.set(id, clean);
    }
  }
}

const out = {
  /** Regenerated by scripts/gen-check-rules.mjs — do not edit by hand. */
  generated: true,
  total: [...byCategory.values()].reduce((n, s) => n + s.size, 0),
  categories: Object.fromEntries(
    [...byCategory].map(([category, ids]) => [
      category,
      {
        count: ids.size,
        ids: [...ids].sort(),
        rules: [...ids].sort().map((id) => ({ id, title: titles.get(id) ?? null })),
      },
    ]),
  ),
};

const target = resolve(repoRoot, "apps/dev/src/content/check-rules.json");
writeFileSync(target, JSON.stringify(out, null, 2) + "\n");

console.log(`check-rules.json: ${out.total} rules across ${byCategory.size} categories`);
for (const [c, { count }] of Object.entries(out.categories)) console.log(`  ${c.padEnd(10)} ${count}`);
